/**
 * Predicts ancient debris from the world seed (Meteor's OreSim technique, ported from
 * a reference client). Anti-xray hides the ore, but with the seed the exact generation can be replayed,
 * then filtered against the visible world so mined or exposed spots drop out.
 *
 * <p>The replay is only right for a server that generated its nether like this version with that seed. Servers
 * that seed a feature apart from the world (Paper {@code feature-seeds}), chunks generated by another Minecraft
 * version, or a wrong seed produce boxes that are all wrong. Two checks guard against that, each trying several
 * feature index offsets: predicted quartz and gold next to air must be there (the seed fits), and visible ancient
 * debris, next to air or lava where no anti-xray hides it, must lie in predicted veins (the debris replay fits).
 * Boxes are drawn only once the debris check passes; a failed check tells the player why.</p>
 */
@ModuleInfo(
        id = "netheritefinder",
        displayName = "NetheriteFinder",
        aliases = {"DebrisFinder", "OreSim"},
        category = ModuleCategory.VISUALS, subcategory = ModuleSubcategory.ESP,
        description = "module.netheritefinder.description")
public final class NetheriteFinder extends Module {

    // DonutSMP's world seed, the reason this module exists; any other server needs its own.
    private static final String DONUT_SMP_SEED = "6608149111735331168";
    // Nether seeds DonutSMP players have recovered (the server has used more than one). Tried after the configured
    // seed; the server's seed hash and the quartz check pick the live one.
    private static final long[] DONUT_SMP_NETHER_SEEDS = {6608149111735331168L, -2803778941596086821L};
    private static final int MAX_BOXES = 2048;
    // Seed check: samples are predicted air-exposed quartz/gold blocks, which no anti-xray hides.
    private static final int QUARTZ_MIN_SAMPLES = 40;
    private static final int QUARTZ_DECISIVE_SAMPLES = 400;
    // Debris check: samples are ancient debris blocks touching air or lava, which no anti-xray hides either. A wrong
    // replay claims one of them about once in thousands, so a handful decides.
    private static final int DEBRIS_MIN_SAMPLES = 5;
    private static final int DEBRIS_DECISIVE_SAMPLES = 15;
    private static final double MATCH_RATE = 0.6;
    private static final double MISMATCH_RATE = 0.2;
    // A server whose chunks were generated by another version can have a different feature list, which shifts
    // feature indices of the decoration step. Each check tries these offsets on its own.
    private static final int MAX_INDEX_OFFSET = 12;
    // Scattered debris lands at most 2 blocks from its chunk-local origin, so an exposed debris block this far
    // inside a chunk can only come from that chunk's own features.
    private static final int DEBRIS_EDGE = 2;
    private static final int DEBRIS_MIN_Y = 8;
    private static final int DEBRIS_MAX_Y = 119;
    private static final List<ResourceKey<PlacedFeature>> DEBRIS = List.of(
            OrePlacements.ORE_ANCIENT_DEBRIS_LARGE, OrePlacements.ORE_ANCIENT_DEBRIS_SMALL);
    private static final List<ResourceKey<PlacedFeature>> CALIBRATION = List.of(
            OrePlacements.ORE_QUARTZ_NETHER, OrePlacements.ORE_GOLD_NETHER,
            OrePlacements.ORE_QUARTZ_DELTAS, OrePlacements.ORE_GOLD_DELTAS);

    private enum Verdict { UNKNOWN, MATCH, MISMATCH }

    /** A seed under test and its quartz/gold tally. */
    private static final class Candidate {
        private final long seed;
        private final OffsetVote quartz = new OffsetVote();

        Candidate(long seed) {
            this.seed = seed;
        }
    }

    /** Tally of predicted samples the world confirms, per feature index offset. */
    private static final class OffsetVote {
        private final int[] samples = new int[2 * MAX_INDEX_OFFSET + 1];
        private final int[] matched = new int[2 * MAX_INDEX_OFFSET + 1];
        private final Set<Long> chunks = new HashSet<>();
        private Verdict verdict = Verdict.UNKNOWN;
        private int best = MAX_INDEX_OFFSET;

        void reset() {
            Arrays.fill(samples, 0);
            Arrays.fill(matched, 0);
            chunks.clear();
            verdict = Verdict.UNKNOWN;
            best = MAX_INDEX_OFFSET;
        }

        /** True once per chunk while undecided: the chunk should be sampled. */
        boolean wants(ChunkPos pos) {
            return verdict == Verdict.UNKNOWN && chunks.add(ChunkPos.pack(pos.x(), pos.z()));
        }

        void add(int offset, int sampleCount, int matchedCount) {
            samples[offset + MAX_INDEX_OFFSET] += sampleCount;
            matched[offset + MAX_INDEX_OFFSET] += matchedCount;
        }

        /**
         * Decides once every offset has {@code minSamples}: a match when the best offset's rate clears
         * {@link #MATCH_RATE}, a mismatch when even the best stays under {@link #MISMATCH_RATE} or is still unclear
         * after {@code decisive} samples. Returns whether the verdict changed.
         */
        boolean decide(int minSamples, int decisive) {
            if (verdict != Verdict.UNKNOWN) return false;
            int bestIndex = -1;
            double bestRate = -1.0;
            for (int i = 0; i < samples.length; i++) {
                // Judging one offset before the others have samples would let a wrong one decide.
                if (samples[i] < minSamples) return false;
                double rate = (double) matched[i] / samples[i];
                if (rate > bestRate) {
                    bestRate = rate;
                    bestIndex = i;
                }
            }
            best = bestIndex;
            if (bestRate >= MATCH_RATE) {
                verdict = Verdict.MATCH;
            } else if (bestRate <= MISMATCH_RATE || samples[bestIndex] >= decisive) {
                verdict = Verdict.MISMATCH;
            }
            return verdict != Verdict.UNKNOWN;
        }

        int offset() {
            return best - MAX_INDEX_OFFSET;
        }

        String detail() {
            return matched[best] + "/" + samples[best];
        }
    }

    // Registry building is slow and the result never changes within a game session.
    private static volatile CompletableFuture<OreSimulation> simulation;

    private final StringValue seed = text("seed", DONUT_SMP_SEED);
    private final NumberValue<Integer> rangeChunks = num("range", 6, 1, 12);
    private final BooleanValue showUnverified = bool("show_unverified", false);
    private final RGBAColorValue fillColor = color("fill_color", "#50BF40BF");
    private final RGBAColorValue lineColor = color("line_color", "#FFD11BF5");

    private final Minecraft mc = Minecraft.getInstance();
    // A vein can reach 2 blocks past its chunk and the air check looks 1 further, so the ring of
    // neighbours must be loaded: an unloaded chunk reads as air and would silently drop the ore.
    private final LoadedChunkScanner<List<BlockPos>> scanner =
            new LoadedChunkScanner<>(this::predict, rangeChunks::get, 6, 3000L, 1);
    private final List<Candidate> candidates = new ArrayList<>();
    // The candidate whose quartz/gold fit this world; debris is predicted from its seed.
    private Candidate active;
    private boolean serverConfirmed;
    private boolean noSeedReported;
    private final OffsetVote debrisVote = new OffsetVote();
    // Index offset of the debris features, set by the debris check.
    private int debrisOffset;
    private ClientLevel calibratedLevel;
    private String scannedSeed = "";

    @Override
    public void onEnable() {
        scanner.clear();
        resetCalibration();
        scannedSeed = "";
        calibratedLevel = null;
        simulation();
    }

    @Override
    public void onDisable() {
        scanner.clear();
        resetCalibration();
    }

    private void resetCalibration() {
        candidates.clear();
        active = null;
        serverConfirmed = false;
        noSeedReported = false;
        debrisVote.reset();
        debrisOffset = 0;
    }

    private static CompletableFuture<OreSimulation> simulation() {
        CompletableFuture<OreSimulation> current = simulation;
        if (current == null || current.isCompletedExceptionally()) {
            synchronized (NetheriteFinder.class) {
                current = simulation;
                if (current == null || current.isCompletedExceptionally()) {
                    current = CompletableFuture.supplyAsync(() -> OreSimulation.forNether(DEBRIS, CALIBRATION));
                    simulation = current;
                }
            }
        }
        return current;
    }

    @EventHandler
    private void onPacketReceive(PacketEvent.Receive event) {
        scanner.onPacket(event.getPacket());
    }

    @Override
    public void onTick() {
        if (!isEnabled() || mc.level == null || mc.player == null) return;
        if (mc.level.dimension() != Level.NETHER) return;

        CompletableFuture<OreSimulation> future = simulation();
        if (future.isCompletedExceptionally()) {
            Throwable cause = future.handle((ok, error) -> error).join();
            DebugLog.error("NetheriteFinder could not build the ore simulation", cause);
            Notifier.error("NetheriteFinder: could not load world-gen data, see log");
            setEnabledInternal(false);
            return;
        }
        if (!future.isDone()) return;

        // Evaluated apart from the seed test, which would otherwise skip noting the level.
        boolean levelChanged = scannerLevelChanged();
        if (!seed.get().equals(scannedSeed) || levelChanged) {
            scannedSeed = seed.get();
            resetCalibration();
            pickCandidates();
            scanner.rescanAll();
        }
        scanner.tick(mc);
        updateVerdict();
    }

    private boolean scannerLevelChanged() {
        if (mc.level == calibratedLevel) return false;
        calibratedLevel = mc.level;
        return true;
    }

    /**
     * Seeds to test in this level: the configured one, then the known DonutSMP nether seeds. The seed hash the server
     * sends narrows them to the one it uses; a hash that matches none is reported, and the seeds are still tested on
     * the terrain in case the hash is fake.
     */
    private void pickCandidates() {
        List<Long> seeds = new ArrayList<>();
        seeds.add(parseSeed(scannedSeed));
        for (long known : DONUT_SMP_NETHER_SEEDS) {
            if (!seeds.contains(known)) seeds.add(known);
        }
        List<Long> confirmed = new ArrayList<>();
        for (long candidate : seeds) {
            if (ServerSeedCheck.matches(mc.level, candidate).orElse(false)) confirmed.add(candidate);
        }
        OptionalLong hashed = ServerSeedCheck.hashedSeed(mc.level);
        if (!confirmed.isEmpty()) {
            seeds = confirmed;
            serverConfirmed = true;
            Notifier.info("NetheriteFinder: the server confirms seed " + confirmed.getFirst()
                    + ", checking its ore generation");
        } else if (hashed.isPresent()) {
            Notifier.warning("NetheriteFinder: this nether's seed is not " + describe(seeds) + " (server seed hash "
                    + Long.toHexString(hashed.getAsLong()) + "). Set its real seed in the module settings.");
        }
        for (long candidate : seeds) candidates.add(new Candidate(candidate));
    }

    private static String describe(List<Long> seeds) {
        StringBuilder text = new StringBuilder();
        for (int i = 0; i < seeds.size(); i++) {
            if (i > 0) text.append(i == seeds.size() - 1 ? " or " : ", ");
            text.append(seeds.get(i));
        }
        return text.toString();
    }

    /** Reports each check's verdict once; a debris offset other than the one predicted with re-predicts every chunk. */
    private void updateVerdict() {
        if (active == null) updateSeedVerdict();
        if (active == null || !debrisVote.decide(DEBRIS_MIN_SAMPLES, DEBRIS_DECISIVE_SAMPLES)) return;
        String detail = debrisVote.detail() + " visible ancient debris predicted";
        if (debrisVote.verdict == Verdict.MATCH) {
            if (debrisVote.offset() != debrisOffset) {
                debrisOffset = debrisVote.offset();
                scanner.rescanAll();
            }
            Notifier.success("NetheriteFinder: debris predictions verified (" + detail
                    + (debrisOffset != 0 ? ", feature index offset " + debrisOffset : "") + ")");
        } else {
            Notifier.warning("NetheriteFinder: this server places ancient debris apart from the world seed (best "
                    + detail + " while quartz/gold fit), e.g. Paper feature-seeds. Debris cannot be predicted "
                    + "here" + (showUnverified.get() ? "." : "; boxes hidden."));
        }
    }

    /** Picks the first candidate whose quartz/gold fit; says so once when none does. */
    private void updateSeedVerdict() {
        boolean allFailed = !candidates.isEmpty();
        for (Candidate candidate : candidates) {
            candidate.quartz.decide(QUARTZ_MIN_SAMPLES, QUARTZ_DECISIVE_SAMPLES);
            if (candidate.quartz.verdict == Verdict.MATCH) {
                active = candidate;
                int offset = candidate.quartz.offset();
                Notifier.info("NetheriteFinder: seed " + candidate.seed + " fits this world ("
                        + candidate.quartz.detail() + " exposed quartz/gold blocks where it puts them"
                        + (offset != 0 ? ", feature index offset " + offset : "") + "). Boxes appear once "
                        + DEBRIS_MIN_SAMPLES + " visible ancient debris (touching air or lava) confirm the debris "
                        + "prediction.");
                // Chunks scanned while the seed was open hold no prediction yet.
                scanner.rescanAll();
                return;
            }
            if (candidate.quartz.verdict != Verdict.MISMATCH) allFailed = false;
        }
        if (!allFailed || noSeedReported) return;
        noSeedReported = true;
        StringBuilder detail = new StringBuilder();
        for (Candidate candidate : candidates) {
            if (!detail.isEmpty()) detail.append(", ");
            detail.append(candidate.seed).append(": ").append(candidate.quartz.detail());
        }
        Notifier.warning("NetheriteFinder: no tried seed generates this nether's quartz/gold (" + detail + ")."
                + (serverConfirmed ? " The server's seed hash matches, so its generator differs from vanilla."
                : " Set the server's real nether seed in the module settings."));
    }

    private List<BlockPos> predict(ClientLevel level, LevelChunk chunk) {
        OreSimulation sim = simulation().getNow(null);
        if (sim == null || level.dimension() != Level.NETHER) return null;
        ChunkPos pos = chunk.getPos();
        if (active == null) {
            for (Candidate candidate : candidates) {
                if (!candidate.quartz.wants(pos)) continue;
                for (int offset = -MAX_INDEX_OFFSET; offset <= MAX_INDEX_OFFSET; offset++) {
                    OreSimulation.Calibration sample = sim.calibrate(level, candidate.seed, pos.x(), pos.z(), offset);
                    candidate.quartz.add(offset, sample.exposed(), sample.matched());
                }
            }
            return null;
        }
        if (debrisVote.wants(pos)) sampleDebris(sim, level, chunk, active.seed);
        List<BlockPos> found = sim.simulate(level, active.seed, pos.x(), pos.z(), debrisOffset);
        return found.isEmpty() ? null : found;
    }

    /** Counts the chunk's visible debris and, per index offset, how many of them the replay's veins claim. */
    private void sampleDebris(OreSimulation sim, ClientLevel level, LevelChunk chunk, long worldSeed) {
        ChunkPos pos = chunk.getPos();
        int minX = pos.getMinBlockX() + DEBRIS_EDGE;
        int maxX = pos.getMaxBlockX() - DEBRIS_EDGE;
        int minZ = pos.getMinBlockZ() + DEBRIS_EDGE;
        int maxZ = pos.getMaxBlockZ() - DEBRIS_EDGE;
        List<BlockPos> visible = new ArrayList<>();
        BlockPos.MutableBlockPos cursor = new BlockPos.MutableBlockPos();
        ChunkBlocks.forEach(chunk, DEBRIS_MIN_Y, DEBRIS_MAX_Y, state -> state.is(Blocks.ANCIENT_DEBRIS),
                (x, y, z, state) -> {
                    if (x >= minX && x <= maxX && z >= minZ && z <= maxZ && exposed(level, cursor.set(x, y, z))) {
                        visible.add(new BlockPos(x, y, z));
                    }
                    return true;
                });
        if (visible.isEmpty()) return;
        for (int offset = -MAX_INDEX_OFFSET; offset <= MAX_INDEX_OFFSET; offset++) {
            List<BlockPos> claimed = sim.veinBlocks(level, worldSeed, pos.x(), pos.z(), offset);
            int hits = 0;
            for (BlockPos block : visible) {
                if (claimed.contains(block)) hits++;
            }
            debrisVote.add(offset, visible.size(), hits);
        }
    }

    // Paper's anti-xray only hides blocks walled in by occluding blocks; air and lava neighbours leave them real.
    private static boolean exposed(ClientLevel level, BlockPos pos) {
        for (Direction direction : Direction.values()) {
            BlockState neighbour = level.getBlockState(pos.relative(direction));
            if (neighbour.isAir() || !neighbour.getFluidState().isEmpty()) return true;
        }
        return false;
    }

    // Numeric seeds parse as-is; anything else goes through String.hashCode, the same rule
    // vanilla applies to a seed typed into the world creation screen.
    private static long parseSeed(String text) {
        String trimmed = text == null ? "" : text.trim();
        try {
            return Long.parseLong(trimmed);
        } catch (NumberFormatException ignored) {
            return trimmed.hashCode();
        }
    }

    @Override
    public WorldPhase getWorldPhase() {
        return WorldPhase.END_MAIN;
    }

    @Override
    public void onRenderWorldEngine(Renderer3D renderer, Renderer3D depthRenderer, float tickDelta) {
        LocalPlayer player = mc.player;
        if (!isEnabled() || renderer == null || player == null || mc.level == null
                || mc.level.dimension() != Level.NETHER) return;
        // Unverified boxes are guesses: a replay that does not fit the world draws boxes that are all wrong.
        if (debrisVote.verdict != Verdict.MATCH && !showUnverified.get()) return;

        FinderRender draw = FinderRender.begin(renderer, 1.0f);
        int fill = fillColor.getArgb();
        int line = lineColor.getArgb();
        int range = rangeChunks.get();
        ChunkPos center = player.chunkPosition();
        Map<Long, List<BlockPos>> results = scanner.results();
        // Walk square rings outward from the player: when MAX_BOXES cuts the list, the ore that
        // gets dropped is the farthest, not whatever the hash map happened to put last.
        int drawn = 0;
        for (int ring = 0; ring <= range; ring++) {
            for (int dx = -ring; dx <= ring; dx++) {
                boolean edgeColumn = dx == -ring || dx == ring;
                for (int dz = -ring; dz <= ring; dz += edgeColumn ? 1 : 2 * ring) {
                    List<BlockPos> ore = results.get(ChunkPos.pack(center.x() + dx, center.z() + dz));
                    if (ore == null) continue;
                    for (BlockPos pos : ore) {
                        draw.blockBox(pos.getX(), pos.getY(), pos.getZ(), fill, line);
                        if (++drawn >= MAX_BOXES) return;
                    }
                }
            }
        }
    }
}
