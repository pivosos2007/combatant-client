    private static final class PreparedSprite implements AutoCloseable {
        private final Timeline timeline;
        private final int frameWidth;
        private final int frameHeight;
        private final int sheetWidth;
        private final int sheetHeight;
        private final NativeImage albedo;
        private final NativeImage normalHeight;
        private final NativeImage surface;
        private final NativeImage specular;
        private final int usableMask;

        private PreparedSprite(Timeline timeline, int frameWidth, int frameHeight, int sheetWidth, int sheetHeight,
                               NativeImage albedo, NativeImage normalHeight, NativeImage surface, NativeImage specular,
                               int usableMask) {
            this.timeline = timeline;
            this.frameWidth = frameWidth;
            this.frameHeight = frameHeight;
            this.sheetWidth = sheetWidth;
            this.sheetHeight = sheetHeight;
            this.albedo = albedo;
            this.normalHeight = normalHeight;
            this.surface = surface;
            this.specular = specular;
            this.usableMask = usableMask;
        }

        private Timeline timeline() { return timeline; }
        private int usableMask() { return usableMask; }

        private FrameSample sample(SpriteContents.AnimationState state) {
            int sequence = 0;
            int subFrame = 0;
            if (state != null) {
                SpriteAnimationStateAccessor accessor = (SpriteAnimationStateAccessor) (Object) state;
                sequence = accessor.combatant$getFrame();
                subFrame = accessor.combatant$getSubFrame();
            }
            return new FrameSample(
                    frame(albedo, timeline, sequence, frameWidth, frameHeight, sheetWidth, sheetHeight, subFrame),
                    frame(normalHeight, timeline, sequence, frameWidth, frameHeight, sheetWidth, sheetHeight, subFrame),
                    frame(surface, timeline, sequence, frameWidth, frameHeight, sheetWidth, sheetHeight, subFrame),
                    frame(specular, timeline, sequence, frameWidth, frameHeight, sheetWidth, sheetHeight, subFrame)
            );
        }

        @Override
        public void close() {
            albedo.close();
            normalHeight.close();
            surface.close();
            specular.close();
        }
    }

    private record FrameSample(NativeImage albedo, NativeImage normalHeight, NativeImage surface, NativeImage specular)
            implements AutoCloseable {
        @Override
        public void close() {
            albedo.close();
            normalHeight.close();
            surface.close();
            specular.close();
        }
    }
